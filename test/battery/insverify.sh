#!/usr/bin/env bash
# Build the working tree and diff its inssweep against the stored
# baseline.  Run from anywhere; everything is absolute.
#
#   insverify.sh [label]          # default label: cur
#
# The baseline lives next to this script in insbase/ and was
# produced at commit cb90ea330c -- phase 22's S3 exit, the last revision
# before the `Insstart` / `compl_*` globals become an owned completion
# session (p22 S5/S6).
#
# WHY IT EXISTS (p22-1 survey, section 3, gap 1).  insexpand is the
# second-largest `cell_ptr` family in the tree -- 215 sites, 24 files,
# 20 interacting globals -- and it had NO differential.  `cxprobe` is
# *cmdline* expansion; `1785449630-insweep.sh` is the TUI INPUT layer;
# `1786233895-editprobe.lua`'s `pum` phase is one line of one probe.
# `test_ins_complete`, `editor/completion_spec` and `ui/popupmenu_spec`
# are point assertions over a twenty-global state machine, and point
# assertions cannot gate a rewrite of the state itself.
#
# THREE ARTIFACTS, TWO LAYERS:
#
#   base.txt     canonical report: ONE LINE PER KEYSTROKE, not per case.
#                mode, `pumvisible()`, `complete_info()`'s mode /
#                selected / item count / preinserted text, the current
#                line, the cursor, a digest of the buffer, a digest of
#                the match WORDS, `pum_getpos()` geometry and
#                `v:completed_item`.  Plus a `/fini` line per case with
#                the autocmd ORDER, the undo delta and the messages.
#                Moving ALONE is a behaviour change a user can see.
#   base.dump    the BULK layer: every match in full
#                (word|abbr|kind|menu|user_data|hl_group), the buffer
#                after every keystroke, `v:completed_item` in full,
#                `complete_info()` verbatim for nine key subsets, and a
#                dying child's stderr.  Moving ALONE means an item FIELD
#                moved with every scalar answer still right.
#   base.stderr  EMPTY at the baseline, and that is the assertion.
#
# THE REPORT CARRIES A `## <section> rows=N` LINE PER SECTION.  At the
# baseline they are:
#
#   i0-canary 5 · i1-sources 180 · i2-cot 188 · i3-ctrlx 126 ·
#   i4-leader 121 · i5-wrap 101 · i6-observe 59 · i7-funcs 125 ·
#   i8-end 78 · i91-abortprobe 13
#
# ... summing to `## TOTAL rows=1017`, with artifacts 1,019 / 8,668 / 0
# lines (the report adds `## TOTAL` and `exit 0`; `i0/attach` and the
# twenty section lines are already counted).
#
# FIVE ROWS ARE THE LOAD-BEARING ASSERTIONS.
#
#   * `i0/attach ui=true`.  The child MUST have a UI.  Without it
#     `pum_getpos()` answers nothing, half of `pum.rs` never runs, and
#     -- worse -- the first error a case provokes puts the child on a
#     HIT-ENTER PROMPT and the sweep HANGS with no output.  The attach
#     asks for `ext_messages` for exactly that reason.
#   * `i0/probe bufs=6 hid=2 tags=3 ulslisted=0 unlloaded=0 win=2`.
#     The world the `'complete'` letters need: a buffer in a window, a
#     loaded hidden one, a listed-unloaded one, an unlisted one and a
#     three-entry tags file.  If any of these is wrong then i1 measures
#     nothing and looks exactly like a healthy section.
#   * `i0/files ...=<digest>` for all eleven fixture files, none
#     `MISSING`.  The spell file is GENERATED by `:mkspell` in the
#     sandbox; if that step fails, `kspell` and CTRL-X CTRL-S go quiet.
#   * `i91/groups cases=12 aborted=0`.  THE SWEEP HAS NO EXPECTED
#     ABORT: any abort at all is a regression, by construction.
#   * EVERY `i1/*/n/k1` and `i3/*/k1` row with a source behind it has
#     `n>0`.  The four that do not are deliberate and named below.
#
# FOUR DELIBERATE ZEROES.  `i1/defs` (`'complete'` = `d`) finds nothing
# while `i3/defs` (CTRL-X CTRL-D) finds three, and that asymmetry is
# UPSTREAM: `get_normal_compl_info` builds `compl_pattern` as the
# regexp `\<INC` unless `ctrl_x_mode_path_defines()`, and `'complete'`
# never sets that mode, so `find_pattern_in_path(FIND_DEFINE)` is handed
# a regexp it cannot match.  `i1/empty` (`'complete'` = ``),
# `i3/evalz` (CTRL-X CTRL-Z is the *stop* key) and `i3/xx` are zero by
# definition.
#
# WHAT IS NOT COVERED, DELIBERATELY.  The completion MESSAGES -- "--
# Keyword completion (^N^P)", "match 1 of 3", "The only match",
# "Pattern not found", "Back at original" -- are `showmode`/`msg_attr`
# text that never reaches `:messages`, and reading them back would mean
# decoding `redraw` notifications into a Lua UI client.  They are
# scrsweep's surface, not this one.  `'autocomplete'` and
# `'autocompletetimeout'` are pinned off: they put a WALL-CLOCK budget
# on match collection (`compl_time_slice_expired`) and a sweep that
# measured a timed collection would not be a baseline.
#
# TAKES ~3 s in the sweep plus the build.  Twelve `--headless --embed`
# children in i91, each reaped before its row is printed, plus one
# standing child for everything else.  If a run is killed, look for
# children with ppid 1 and KILL THEM BY PID -- never by pattern, which
# would take out the operator's own editor.
#
# ONE TRAP FOR A LATER SLICE.  Every digest is taken over text
# NORMALISED IN THE CHILD (`_G.NORM`), not over the raw string: $WORK is
# a fresh `mktemp -d` on every run and CTRL-X CTRL-F completes real
# paths, so a digest over the raw text moves every run while the
# sed-scrubbed artifact around it stays put.  A new digest that skips
# `NORM` makes the row flap and looks like a real regression.
#
# When a slice *adds* cases, land the additions against unchanged
# behaviour first (0 removed lines, N added), re-baseline, and only then
# land the behaviour change.
#
# Regenerate the baseline only when a behaviour change is *intended* and
# reviewed:
#
#   inssweep.sh <nvim> <runtime> \
#       test/battery/insbase base
#
# ... and `just build` first: a mutation harness leaves the binary built
# from its last mutant, and a baseline taken from that compares mutant
# against mutant forever after.
set -euo pipefail

HERE=$(cd "$(dirname "$0")" && pwd)
BASELINE=${INS_BASELINE:-$HERE/insbase}
OUT=${SWEEP_OUT:-/tmp/inssweep-out}
REPO=${REPO:-$(cd "$HERE/../.." && pwd)}
LABEL=${1:-cur}
LOG=$OUT/build-$LABEL.log

mkdir -p "$OUT"
cd "$REPO"
if ! just build >"$LOG" 2>&1; then
  echo "BUILD FAILED -- see $LOG" >&2
  grep -E '^(error|warning)' "$LOG" | head -60 >&2
  exit 1
fi

rm -f "$OUT/$LABEL.txt" "$OUT/$LABEL.dump" "$OUT/$LABEL.stderr"
"$HERE/inssweep.sh" "$REPO/target/debug/nvim" "$REPO/runtime" \
  "$OUT" "$LABEL" 2>&1 | tail -1

fail=0
for part in txt dump stderr; do
  if diff -q "$BASELINE/base.$part" "$OUT/$LABEL.$part" >/dev/null; then
    echo "$part: IDENTICAL"
  else
    echo "$part: DIFFERS"
    # `|| true`: `set -e` plus `pipefail` would abort on the first
    # differing artifact and the ones that say *which* layer moved would
    # never be compared.
    diff -a "$BASELINE/base.$part" "$OUT/$LABEL.$part" | head -60 || true
    fail=1
  fi
done
exit $fail
