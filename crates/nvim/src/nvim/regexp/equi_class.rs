//! `[[=a=]]`: the equivalence classes both engines expand a bracketed
//! equivalence expression into. Latin-1, Latin-9 and UTF-8 only, matching
//! upstream.
//!
//! Upstream keeps this data twice — once as a `switch` in the backtracking
//! compiler (`reg_equi_class`) and once, macro-expanded, in the NFA compiler
//! (`nfa_emit_equi_class`) — with a comment on each telling you to update the
//! other. The two had drifted, so the table below records the drift instead of
//! silently picking a winner: see [`EquiClass::nfa_only`].
//!
//! Upstream also emits the members of a class in a slightly different order in
//! the two copies for eight of the classes. Order is not observable — both
//! engines are building a set membership test out of the members — so this
//! table keeps one order (the backtracking compiler's) and both engines walk
//! it.

#![forbid(unsafe_code)]

use core::ffi::c_int;

/// One equivalence class: every character that belongs to it.
pub(crate) struct EquiClass {
    /// The members both of upstream's copies agree on, in the order the
    /// backtracking compiler emitted them.
    members: &'static [u32],
    /// Members present only in upstream's NFA copy of the table. Two
    /// accidents of drift between the two hand-maintained switches, kept
    /// because they are what each engine actually did:
    ///
    /// - `U+0200` is in the NFA copy's `A` class and not the backtracking
    ///   copy's, so `[[=\u{200}=]]` really does mean different things to the
    ///   two engines.
    /// - the NFA copy lists `U+1ECB` twice in the `i` class, which is
    ///   invisible in a set but keeps the emitted postfix identical.
    nfa_only: &'static [u32],
}

impl EquiClass {
    /// The class as the backtracking compiler sees it.
    pub(crate) fn backtracking_members(&self) -> impl Iterator<Item = c_int> + '_ {
        self.members.iter().map(|&c| c as c_int)
    }

    /// The class as the NFA compiler sees it.
    pub(crate) fn nfa_members(&self) -> impl Iterator<Item = c_int> + '_ {
        self.members
            .iter()
            .chain(self.nfa_only)
            .map(|&c| c as c_int)
    }
}

/// The class containing `c` as the backtracking compiler sees it, if any.
pub(crate) fn backtracking_class_of(c: c_int) -> Option<&'static EquiClass> {
    let c = u32::try_from(c).ok()?;
    CLASSES.iter().find(|class| class.members.contains(&c))
}

/// The class containing `c` as the NFA compiler sees it, if any.
pub(crate) fn nfa_class_of(c: c_int) -> Option<&'static EquiClass> {
    let c = u32::try_from(c).ok()?;
    CLASSES
        .iter()
        .find(|class| class.members.contains(&c) || class.nfa_only.contains(&c))
}

